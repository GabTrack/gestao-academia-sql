USE ACADEMIA;

-- ======================================================
-- 1. RELATÓRIOS FINANCEIROS E RECEITA
-- ======================================================

-- 1.1 Faturamento Mensal Consolidado
SELECT 
    DATE_FORMAT(DATA, "%y-%m") AS DATA_REFERENCIA,
    SUM(VALOR) AS VALOR_ARRECADADO
FROM PAGAMENTO
GROUP BY DATE_FORMAT(DATA, "%y-%m")
ORDER BY DATE_FORMAT(DATA, "%y-%m");

-- 1.2 Status Financeiro dos Alunos (Adimplente vs Inadimplente)
WITH ALUNO_PGTO AS (
    SELECT 
        A.IDALUNO,
        A.NOME,
        P.PRECO
    FROM ALUNO A
    INNER JOIN PLANO P ON A.IDALUNO = P.ID_ALUNO
)
SELECT 
    T.NOME,
    T.PRECO,
    SUM(IFNULL(PA.VALOR, 0)) AS TOTAL_PAGO,
    CASE 
       WHEN SUM(IFNULL(PA.VALOR, 0)) > T.PRECO THEN 'ADIMPLENTE'
       ELSE 'INADIMPLENTE'
    END AS STATUS
FROM ALUNO_PGTO T
INNER JOIN PAGAMENTO PA ON T.IDALUNO = PA.ID_ALUNO
GROUP BY T.NOME, T.PRECO;

-- ======================================================
-- 2. RANKINGS E WINDOW FUNCTIONS
-- ======================================================

-- 2.1 Ranking Geral de Alunos por Total Pago (DENSE_RANK)
SELECT
    A.IDALUNO, 
    A.NOME,
    S.SOMA,
    DENSE_RANK() OVER(ORDER BY S.SOMA DESC) AS RANKING_PAGAMENTOS
FROM ALUNO A
INNER JOIN (
    SELECT ID_ALUNO, SUM(VALOR) AS SOMA
    FROM PAGAMENTO
    GROUP BY ID_ALUNO
) S ON S.ID_ALUNO = A.IDALUNO;

-- 2.2 Evolução Histórica de Pagamentos por Aluno (Running Total)
SELECT 
    A.IDALUNO,
    A.NOME,
    P.DATA,
    P.VALOR,
    SUM(P.VALOR) OVER(PARTITION BY A.IDALUNO ORDER BY P.DATA) AS TOTAL_ACUMULADO
FROM ALUNO A
INNER JOIN PAGAMENTO P ON A.IDALUNO = P.ID_ALUNO;

-- ======================================================
-- 3. GESTÃO DE PROFESSORES E DESEMPENHO
-- ======================================================

-- 3.1 Ranking de Professores por Quantidade de Alunos
WITH TOTAL_ALUNOS AS (
    SELECT 
        P.IDPROFESSOR, 
        P.NOME,
        COUNT(DISTINCT T.ID_ALUNO) AS QUANTIDADE_ALUNOS
    FROM PROFESSOR P
    INNER JOIN TREINO T ON P.IDPROFESSOR = T.ID_PROFESSOR
    GROUP BY P.IDPROFESSOR, P.NOME
)
SELECT 
    IDPROFESSOR,
    NOME,
    QUANTIDADE_ALUNOS,
    ROW_NUMBER() OVER(ORDER BY QUANTIDADE_ALUNOS DESC) AS RANKING_PROFESSOR
FROM TOTAL_ALUNOS;

-- 3.2 Receita Gerada por Professor vs Média do Professor
WITH TOTAL_ALUNO AS (
    SELECT
        PR.NOME AS NOME_PROFESSOR,
        T.ID_PROFESSOR,
        A.IDALUNO,
        SUM(P.VALOR) AS TOTAL
    FROM ALUNO A
    INNER JOIN PAGAMENTO P ON A.IDALUNO = P.ID_ALUNO
    INNER JOIN TREINO T ON A.IDALUNO = T.ID_ALUNO
    INNER JOIN PROFESSOR PR ON T.ID_PROFESSOR = PR.IDPROFESSOR
    GROUP BY T.ID_PROFESSOR, A.NOME, A.IDALUNO
),
MEDIA_PROFESSOR AS (
    SELECT 
        ID_PROFESSOR,
        TRUNCATE(AVG(TOTAL), 2) AS MEDIA
    FROM TOTAL_ALUNO
    GROUP BY ID_PROFESSOR
)
SELECT 
    TA.ID_PROFESSOR,
    TA.NOME_PROFESSOR,
    TA.TOTAL AS RECEITA_TOTAL
FROM TOTAL_ALUNO TA
INNER JOIN MEDIA_PROFESSOR MP ON TA.ID_PROFESSOR = MP.ID_PROFESSOR
WHERE TA.TOTAL > MP.MEDIA;

-- 3.3 Identificar Professores Sem Alunos Pagantes (Usando NOT EXISTS)
SELECT DISTINCT P.NOME
FROM PROFESSOR P
WHERE NOT EXISTS (
    SELECT 1
    FROM TREINO T
    INNER JOIN PAGAMENTO PA ON T.ID_ALUNO = PA.ID_ALUNO
    WHERE P.IDPROFESSOR = T.ID_PROFESSOR
);

-- ======================================================
-- 4. DESAFIO BÔNUS: DASHBOARD EXECUTIVO GERAL
-- ======================================================

-- 4.1 KPIs Consolidados da Academia em Linha Única
WITH RECEITA AS (SELECT SUM(VALOR) AS RECEITA_TOTAL FROM PAGAMENTO),
     MAIOR_PAGAMENTO AS (SELECT MAX(VALOR) AS MAIOR FROM PAGAMENTO), 
     MENOR_PAGAMENTO AS (SELECT MIN(VALOR) AS MENOR FROM PAGAMENTO),
     QUANTIDADE_ALUNOS AS (SELECT COUNT(IDALUNO) AS ALUNOS FROM ALUNO),
     QUANTIDADE_PROFESSORES AS (SELECT COUNT(IDPROFESSOR) AS PROFESSORES FROM PROFESSOR),
     TICKET_MEDIO AS (SELECT TRUNCATE(AVG(VALOR), 2) AS TICKET_MEDIO FROM PAGAMENTO)

SELECT 
    R.RECEITA_TOTAL,
    MP.MAIOR AS MAIOR_PGTO,
    MA.MENOR AS MENOR_PGTO,
    QA.ALUNOS AS TOTAL_ALUNOS,
    QP.PROFESSORES AS TOTAL_PROFESSORES,
    TM.TICKET_MEDIO
FROM 
    RECEITA R, 
    MAIOR_PAGAMENTO MP, 
    MENOR_PAGAMENTO MA, 
    QUANTIDADE_ALUNOS QA, 
    QUANTIDADE_PROFESSORES QP, 
    TICKET_MEDIO TM;