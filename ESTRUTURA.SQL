DROP DATABASE IF EXISTS ACADEMIA;
CREATE DATABASE ACADEMIA;
USE ACADEMIA;

-- 1. CRIAÇÃO DAS TABELAS INDEPENDENTES E COM CHAVES ESTRANGEIRAS

CREATE TABLE ALUNO (
    IDALUNO INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(30) NOT NULL,
    SEXO ENUM('F', 'M') NOT NULL,
    CPF CHAR(11) NOT NULL UNIQUE,
    NASCIMENTO DATE NOT NULL,
    DATA_MATRICULA DATE NOT NULL,
    TIPO_TEL ENUM('CEL', 'RES', 'COM'), 
    TELEFONE VARCHAR(11), 
    EMAIL VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE ENDERECO (
    IDENDERECO INT AUTO_INCREMENT PRIMARY KEY,
    RUA VARCHAR(30) NOT NULL,
    BAIRRO VARCHAR(30) NOT NULL,
    CIDADE VARCHAR(30) NOT NULL,
    ESTADO CHAR(2) NOT NULL,
    ID_ALUNO INT NOT NULL UNIQUE,
    CONSTRAINT FK_ENDERECO_ALUNO FOREIGN KEY (ID_ALUNO) REFERENCES ALUNO (IDALUNO)
);

CREATE TABLE PROFESSOR (
    IDPROFESSOR INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(30) NOT NULL,
    HORARIO ENUM('MANHA', 'TARDE', 'NOITE') NOT NULL,
    ESPECIALIDADE VARCHAR(15) 
);

CREATE TABLE EXERCICIO (
    IDEXERCICIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE DURACAO (
    IDDURACAO INT AUTO_INCREMENT PRIMARY KEY,
    MESES ENUM('3', '6', '9') NOT NULL
);

-- 2. CRIAÇÃO DAS TABELAS DEPENDENTES

CREATE TABLE TREINO (
    IDTREINO INT AUTO_INCREMENT PRIMARY KEY,
    OBJETIVO VARCHAR(15) NOT NULL,
    DATA DATE NOT NULL,
    ID_PROFESSOR INT NOT NULL,
    ID_ALUNO INT NOT NULL,
    CONSTRAINT FK_TREINO_PROFESSOR FOREIGN KEY (ID_PROFESSOR) REFERENCES PROFESSOR (IDPROFESSOR),
    CONSTRAINT FK_TREINO_ALUNO FOREIGN KEY (ID_ALUNO) REFERENCES ALUNO (IDALUNO)
);

CREATE TABLE TREINO_EXERCICIO (
    SERIES INT NOT NULL,
    REPETICOES INT NOT NULL,
    ID_EXERCICIO INT NOT NULL,
    ID_TREINO INT NOT NULL,
    PRIMARY KEY (ID_EXERCICIO, ID_TREINO),
    CONSTRAINT FK_TRE_EXE_EXERCICIO FOREIGN KEY (ID_EXERCICIO) REFERENCES EXERCICIO (IDEXERCICIO),
    CONSTRAINT FK_TRE_EXE_TREINO FOREIGN KEY (ID_TREINO) REFERENCES TREINO (IDTREINO)
);

CREATE TABLE PLANO (
    IDPLANO INT AUTO_INCREMENT PRIMARY KEY,
    NOME ENUM('FRANGO', 'INTERMEDIRAIO', 'MAROMBA') NOT NULL,
    PRECO DECIMAL(10,2) NOT NULL,
    ID_DURACAO INT NOT NULL,
    ID_ALUNO INT NOT NULL,
    CONSTRAINT FK_PLANO_DURACAO FOREIGN KEY (ID_DURACAO) REFERENCES DURACAO (IDDURACAO),
    CONSTRAINT FK_PLANO_ALUNO FOREIGN KEY (ID_ALUNO) REFERENCES ALUNO (IDALUNO)
);

CREATE TABLE PAGAMENTO (
    IDPAGAMENTO INT AUTO_INCREMENT PRIMARY KEY,
    METODO ENUM('DEBITO', 'PIX', 'CREDITO', 'CASH') NOT NULL,
    VALOR DECIMAL(10,2) NOT NULL,
    DATA DATE NOT NULL,
    ID_ALUNO INT NOT NULL,
    CONSTRAINT FK_PGTO_ALUNO FOREIGN KEY (ID_ALUNO) REFERENCES ALUNO (IDALUNO)
);

-- ======================================================
-- 3. TRIGGERS DE VALIDAÇÃO DE NEGÓCIO
-- ======================================================

DELIMITER #

CREATE TRIGGER ALUNO_BI_TIPO_NUMERO
BEFORE INSERT ON ALUNO
FOR EACH ROW
BEGIN
    IF (NEW.TIPO_TEL IS NULL AND NEW.TELEFONE IS NOT NULL) OR 
       (NEW.TIPO_TEL IS NOT NULL AND NEW.TELEFONE IS NULL) THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'ERRO: TIPO E TELEFONE DEVEM SER INFORMADOS JUNTOS';
    END IF;
END#

CREATE TRIGGER ALUNO_BU_TIPO_NUMERO
BEFORE UPDATE ON ALUNO
FOR EACH ROW
BEGIN
    IF (NEW.TIPO_TEL IS NULL AND NEW.TELEFONE IS NOT NULL) OR 
       (NEW.TIPO_TEL IS NOT NULL AND NEW.TELEFONE IS NULL) THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'ERRO: TIPO E TELEFONE DEVEM SER INFORMADOS JUNTOS';
    END IF;
END#

DELIMITER ;